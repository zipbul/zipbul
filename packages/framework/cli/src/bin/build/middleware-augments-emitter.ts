/**
 * Emission helpers for `zb build middleware` — renders the consumer-facing
 * `dist/context-augments.d.ts` (declaration merging) and models the versioned
 * `dist/context-augments.json` manifest the app AOT compiler consumes.
 *
 * @public
 */
import { is } from '@zipbul/gildash';
import type { Node as AstNode, ParsedFile } from '@zipbul/gildash';

import { ImportRegistry } from '../../compiler/generator/import-registry';

/**
 * Manifest schema version — readers hard-error on unknown versions. Bumped to
 * 2 when the augment entry shape changed incompatibly: single `validated-accessor`
 * kind (two-kind system removed), `typeRef` dropped.
 */
export const CONTEXT_AUGMENTS_MANIFEST_VERSION = 2;

/**
 * One augment entry in the manifest (JSON-serializable).
 *
 * @public
 */
export interface ManifestAugment {
  readonly ns: string;
  readonly prop: string;
  readonly kind: 'validated-accessor';
}

/**
 * One middleware export in the manifest, keyed by `exportName`.
 *
 * @public
 */
export interface ManifestMiddleware {
  readonly exportName: string;
  readonly form: 1 | 2;
  readonly contextType: string | null;
  readonly augments: readonly ManifestAugment[];
  /** Producer/consumer ops (`ctx.set/use/get`) — MANDATORY (dependency-validation fence). */
  readonly contextOps: ReadonlyArray<{ readonly kind: 'set' | 'use' | 'get'; readonly keyIdentifier: string | null }>;
}

/**
 * `dist/context-augments.json` shape.
 *
 * @public
 */
export interface ContextAugmentsManifest {
  readonly version: typeof CONTEXT_AUGMENTS_MANIFEST_VERSION;
  readonly middlewares: readonly ManifestMiddleware[];
}

/**
 * Namespace resolution result for one `augments.<ns>` entry — where the
 * declaration merging lands.
 *
 * @public
 */
export interface ResolvedAugmentTarget {
  /** Adapter package specifier — the `declare module '<module>'` target. */
  readonly module: string;
  /** Interface name inside the module (e.g. `HttpRequest`). */
  readonly interface: string;
  /** Adapter context class name (e.g. `HttpContext`). */
  readonly contextType: string;
}

/**
 * One interface member for the `.d.ts` render.
 *
 * @public
 */
export interface AugmentDtsMember {
  readonly target: ResolvedAugmentTarget;
  readonly prop: string;
  readonly kind: 'validated-accessor';
}

/**
 * Renders `context-augments.d.ts`: `import type` lines + one
 * `declare module` block per adapter module. Returns `null` when there is
 * nothing to declare.
 *
 * validatedAccessor members render the standardized generated signature
 * `<T>(dto: Class<T>): T` with `Class` imported from `@zipbul/common`.
 *
 * @public
 */
export function renderContextAugmentsDts(
  members: readonly AugmentDtsMember[],
  projectRoot: string,
): string | null {
  if (members.length === 0) return null;

  const registry = new ImportRegistry(projectRoot);
  // module → interface → member lines
  const grouped = new Map<string, Map<string, string[]>>();

  for (const member of members) {
    const line = renderMember(member, registry);
    let interfaces = grouped.get(member.target.module);

    if (interfaces === undefined) {
      interfaces = new Map<string, string[]>();
      grouped.set(member.target.module, interfaces);
    }

    const lines = interfaces.get(member.target.interface) ?? [];

    lines.push(line);
    interfaces.set(member.target.interface, lines);
  }

  const blocks: string[] = [];

  for (const [moduleName, interfaces] of grouped) {
    const lines: string[] = [`declare module '${moduleName}' {`];

    for (const [iface, props] of interfaces) {
      lines.push(`  interface ${iface} {`);
      lines.push(...props.map(p => `    ${p}`));
      lines.push('  }');
    }

    lines.push('}');
    blocks.push(lines.join('\n'));
  }

  const importLines = registry.getImportStatements()
    .map(line => line.replace(/^import \{/, 'import type {'));
  const header = '// AUTO-GENERATED by `zb build middleware` — DO NOT EDIT.\n// Derived from the package\'s declarative middleware `augments` slots.';

  // The file MUST be a module so each `declare module` is a module
  // AUGMENTATION (merging into the adapter's real types) rather than an
  // ambient declaration replacing them. Imports already force module mode;
  // `export {};` covers the imports-free case.
  const moduleLines = importLines.length > 0 ? importLines : ['export {};'];

  return `${header}\n\n${moduleLines.join('\n')}\n\n${blocks.join('\n\n')}\n`;
}

function renderMember(member: AugmentDtsMember, registry: ImportRegistry): string {
  // Every augment is a DTO-validated accessor — render the standardized
  // generated signature with `Class` imported from `@zipbul/common`.
  const classAlias = registry.getAlias('Class', '@zipbul/common');

  return `${member.prop}<T>(dto: ${classAlias}<T>): T;`;
}

/**
 * Exported-name surface of the package entry file, following relative
 * re-export chains (`export { x } from './src/a'`, `export * from './src/b'`)
 * across the parsed source set. `export * from '<external-pkg>'` cannot be
 * enumerated statically — it flips `hasExternalStar` so the entry-export
 * check degrades to permissive instead of false-negative.
 *
 * @public
 */
export interface PackageEntryExports {
  readonly names: ReadonlySet<string>;
  readonly hasExternalStar: boolean;
}

/**
 * Collects the entry file's exported names. `parsedFiles` keys are
 * projectRoot-relative POSIX paths (the build's source set).
 *
 * @public
 */
export function collectPackageEntryExports(
  entryFile: string,
  parsedFiles: ReadonlyMap<string, ParsedFile>,
): PackageEntryExports {
  const names = new Set<string>();
  let hasExternalStar = false;
  const visited = new Set<string>();

  const visit = (filePath: string): void => {
    if (visited.has(filePath)) return;
    visited.add(filePath);

    const parsed = parsedFiles.get(filePath);

    if (parsed === undefined) return;

    for (const stmt of parsed.program.body as readonly AstNode[]) {
      if (is.ExportAllDeclaration(stmt)) {
        const source = stmt.source.value;

        if (typeof source !== 'string') continue;

        const resolved = resolveRelativeModule(filePath, source, parsedFiles);

        if (resolved === null) {
          hasExternalStar = true;
        } else {
          visitAll(resolved);
        }
        continue;
      }

      if (!is.ExportNamedDeclaration(stmt)) continue;

      collectDeclarationNames(stmt.declaration ?? null, names);

      for (const spec of stmt.specifiers ?? []) {
        const exported = (spec as AstNode & { exported?: AstNode }).exported;

        if (exported === undefined) continue;
        if (is.Identifier(exported)) names.add(exported.name);
      }
    }
  };

  // `export *` recursion collects the TARGET file's full export surface.
  const visitAll = (filePath: string): void => {
    visit(filePath);
  };

  visit(entryFile);

  return { names, hasExternalStar };
}

/** Names declared by an `export <declaration>` statement. */
function collectDeclarationNames(declaration: AstNode | null, out: Set<string>): void {
  if (declaration === null) return;

  if (is.VariableDeclaration(declaration)) {
    for (const d of declaration.declarations) {
      if (is.Identifier(d.id)) out.add(d.id.name);
    }
    return;
  }

  const id = (declaration as AstNode & { id?: AstNode | null }).id;

  if (id !== null && id !== undefined && is.Identifier(id)) {
    out.add(id.name);
  }
}

/**
 * Resolves a relative module specifier against the parsed source set
 * (`./src/foo` → `src/foo.ts` | `src/foo/index.ts`). Returns `null` for
 * bare (external) specifiers or unresolvable paths.
 */
function resolveRelativeModule(
  fromFile: string,
  specifier: string,
  parsedFiles: ReadonlyMap<string, ParsedFile>,
): string | null {
  if (!specifier.startsWith('.')) return null;

  const fromDir = fromFile.includes('/') ? fromFile.slice(0, fromFile.lastIndexOf('/')) : '';
  const joined = normalizePath(fromDir === '' ? specifier : `${fromDir}/${specifier}`);

  for (const candidate of [`${joined}.ts`, `${joined}/index.ts`, joined]) {
    if (parsedFiles.has(candidate)) return candidate;
  }

  return null;
}

/** POSIX-normalizes `a/./b/../c` segments without touching the filesystem. */
function normalizePath(path: string): string {
  const segments: string[] = [];

  for (const segment of path.split('/')) {
    if (segment === '' || segment === '.') continue;
    if (segment === '..') {
      segments.pop();
      continue;
    }
    segments.push(segment);
  }

  return segments.join('/');
}
